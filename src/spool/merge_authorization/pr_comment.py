from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any


class PRCommentError(RuntimeError):
    pass


VERDICT_LABELS = {
    "continue": "Ready to continue",
    "human_review": "Needs human review",
    "repair": "Needs repair",
    "stop": "Do not merge",
}


def load_report(path: str | Path) -> dict[str, Any]:
    report_path = Path(path)
    try:
        return json.loads(report_path.read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise PRCommentError(f"Could not read trust report: {report_path} was not found.") from exc
    except json.JSONDecodeError as exc:
        raise PRCommentError(f"Could not parse trust report JSON: {exc}") from exc


def render_pr_comment(payload: dict[str, Any]) -> str:
    verdict = str(payload.get("overall_verdict") or "unknown")
    summary = dict(payload.get("summary") or {})
    scope = dict(payload.get("scope") or {})
    evidence = dict(payload.get("evidence_coverage") or {})
    checks = dict(payload.get("ci_checks") or {})
    decision_memory = dict(payload.get("decision_memory") or {})
    reviewer_actions = list(payload.get("reviewer_actions") or [])
    weak_or_missing = list(payload.get("weak_or_missing_evidence") or [])
    risks = list(payload.get("risks") or [])

    supported_claims = _int_value(summary.get("supported_claims_count"))
    unsupported_claims = _int_value(summary.get("unsupported_claims_count"))
    weak_count = len(weak_or_missing)
    allowed_scope_status = str(summary.get("allowed_scope_status") or "unknown")
    decision_memory_status = str(
        summary.get("decision_memory_status")
        or decision_memory.get("status")
        or "unknown"
    )
    scope_violations = [str(item) for item in scope.get("scope_violations") or [] if item]

    lines = [
        "## Spool Merge Authorization",
        "",
        f"**Verdict:** {VERDICT_LABELS.get(verdict, 'Unknown')} (`{verdict}`)  ",
        f"**Scope:** {allowed_scope_status}  ",
        f"**Agent claims:** {supported_claims} supported, {unsupported_claims} unsupported  ",
    ]
    if weak_count:
        lines.append(f"**Weak/missing evidence:** {weak_count}  ")
    if scope_violations:
        lines.append(f"**Scope violations:** {_inline_code_join(scope_violations)}  ")
    lines.append(f"**Test evidence:** {_test_evidence_line(evidence, checks)}  ")
    lines.append(f"**Decision memory:** {decision_memory_status}  ")
    lines.extend(["", "### Why this verdict?", ""])
    lines.extend([f"- {bullet}" for bullet in _why_bullets(payload)])
    if risks:
        lines.extend(["", "### Risks", ""])
        lines.extend([f"- {risk}" for risk in risks[:3]])
    lines.extend(["", "### Reviewer actions", ""])
    if reviewer_actions:
        lines.extend([f"- {action}" for action in reviewer_actions])
    else:
        lines.append("- None")
    lines.extend(["", "<sub>Generated by Spool from `trust_report.json`.</sub>"])
    return "\n".join(lines).rstrip() + "\n"


def write_comment(path: str | Path, text: str) -> Path:
    output_path = Path(path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(text, encoding="utf-8")
    return output_path


def post_comment(pr_ref: str, body_file: str | Path) -> None:
    command = ["gh", "pr", "comment", str(pr_ref), "--body-file", str(body_file)]
    try:
        subprocess.run(command, text=True, capture_output=True, check=True)
    except FileNotFoundError as exc:
        raise PRCommentError("GitHub CLI `gh` is not installed or is not on PATH.") from exc
    except subprocess.CalledProcessError as exc:
        message = (exc.stderr or exc.stdout or "").strip()
        detail = f": {message}" if message else ""
        raise PRCommentError(f"Could not post PR comment with `gh pr comment`{detail}") from exc


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Render or post a concise Spool PR comment from trust_report.json.")
    parser.add_argument("pr", help="GitHub PR number, URL, or branch understood by `gh pr comment`.")
    parser.add_argument("--report", required=True, help="Path to trust_report.json.")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--dry-run", action="store_true", help="Print the rendered comment and never call GitHub.")
    mode.add_argument("--post", action="store_true", help="Post the rendered comment with `gh pr comment`.")
    parser.add_argument("--out", help="Optional file path to write the rendered comment Markdown.")
    args = parser.parse_args(argv)

    try:
        payload = load_report(args.report)
        comment = render_pr_comment(payload)
        output_path = Path(args.out) if args.out else None
        if output_path is not None:
            write_comment(output_path, comment)
        if args.post:
            body_file = output_path or _write_temp_comment(comment)
            post_comment(args.pr, body_file)
            print(f"posted_comment_pr: {args.pr}")
            print(f"comment_path: {Path(body_file).resolve()}")
            return 0
        if args.dry_run or output_path is None:
            print(comment, end="")
        if output_path is not None:
            print(f"comment_path: {output_path.resolve()}")
        return 0
    except PRCommentError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1


def _write_temp_comment(text: str) -> Path:
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", suffix=".md", delete=False) as handle:
        handle.write(text)
        return Path(handle.name)


def _int_value(value: Any) -> int:
    try:
        return int(value or 0)
    except (TypeError, ValueError):
        return 0


def _inline_code_join(items: list[str]) -> str:
    if not items:
        return "None"
    return ", ".join(f"`{item}`" for item in items)


def _test_evidence_line(evidence: dict[str, Any], checks: dict[str, Any]) -> str:
    checks_status = str(checks.get("status") or evidence.get("ci_checks") or "unknown")
    test_output_status = str(evidence.get("test_output") or "unknown")
    failed_checks = [str(item) for item in checks.get("failed_checks") or [] if item]
    pending_checks = [str(item) for item in checks.get("pending_checks") or [] if item]

    if checks_status == "available":
        if failed_checks:
            return "GitHub checks failing"
        if pending_checks:
            return "GitHub checks pending"
        return "GitHub checks available and passing"
    if test_output_status == "available":
        if checks_status == "unavailable":
            return "PR body tests available; GitHub checks unavailable"
        if checks_status == "empty":
            return "PR body tests available; GitHub checks empty"
        if checks_status == "not_supported":
            return "PR body tests available; GitHub checks not supported"
        return "PR body tests available"
    if test_output_status in {"not_provided", "empty"} and checks_status == "unavailable":
        return "No PR body tests available; GitHub checks unavailable"
    return "unknown"


def _why_bullets(payload: dict[str, Any]) -> list[str]:
    summary = dict(payload.get("summary") or {})
    scope = dict(payload.get("scope") or {})
    evidence = dict(payload.get("evidence_coverage") or {})
    checks = dict(payload.get("ci_checks") or {})
    weak_or_missing = list(payload.get("weak_or_missing_evidence") or [])
    verdict = str(payload.get("overall_verdict") or "unknown")
    supported_claims = _int_value(summary.get("supported_claims_count"))
    unsupported_claims = _int_value(summary.get("unsupported_claims_count"))
    allowed_scope_status = str(summary.get("allowed_scope_status") or "unknown")
    scope_violations = [str(item) for item in scope.get("scope_violations") or [] if item]
    failed_checks = [str(item) for item in checks.get("failed_checks") or [] if item]
    pending_checks = [str(item) for item in checks.get("pending_checks") or [] if item]
    bullets: list[str] = []

    if verdict in {"repair", "stop"} and scope_violations:
        bullets.append(f"Scope violations were found: {_inline_code_join(scope_violations)}.")
    elif verdict in {"repair", "stop"} and failed_checks:
        bullets.append(f"GitHub checks include failures: {_inline_code_join(failed_checks)}.")
    elif verdict == "human_review" and weak_or_missing:
        count = len(weak_or_missing)
        bullets.append(f"Spool found {count} weak or missing evidence item{'s' if count != 1 else ''}.")

    assignment_status = str(evidence.get("assignment") or "unknown")
    if assignment_status == "available":
        bullets.append("Assignment was extracted from `## Spool Task`.")
    elif assignment_status in {"not_provided", "empty", "missing"}:
        bullets.append("Assignment evidence was incomplete, so authorization review is partial.")

    if allowed_scope_status == "within_allowed_scope":
        bullets.append("Changed files are within the allowed files/areas.")
    elif allowed_scope_status == "outside_allowed_scope" and not scope_violations:
        bullets.append("Some changed files appear to be outside the allowed files/areas.")

    if unsupported_claims == 0 and supported_claims > 0:
        bullets.append("No unsupported agent claims were found.")
    elif unsupported_claims > 0:
        bullets.append(f"Spool found {unsupported_claims} unsupported agent claim{'s' if unsupported_claims != 1 else ''}.")

    checks_status = str(checks.get("status") or evidence.get("ci_checks") or "unknown")
    test_output_status = str(evidence.get("test_output") or "unknown")
    if checks_status == "available" and failed_checks:
        bullets.append(f"GitHub checks include failures: {_inline_code_join(failed_checks)}.")
    elif checks_status == "available" and pending_checks:
        bullets.append(f"GitHub checks are still pending: {_inline_code_join(pending_checks)}.")
    elif checks_status == "available":
        bullets.append("GitHub checks are available and passing.")
    elif checks_status in {"unavailable", "empty"} and test_output_status == "available":
        qualifier = "unavailable" if checks_status == "unavailable" else "not reported"
        bullets.append(f"GitHub checks were {qualifier} for this PR, so Spool used PR body test evidence.")

    if not bullets:
        bullets.append("Spool rendered this summary from the available merge authorization report fields.")
    return bullets[:5]


if __name__ == "__main__":
    raise SystemExit(main())
